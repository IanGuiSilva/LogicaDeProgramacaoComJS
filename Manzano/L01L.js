alert("Saiba a soma dos quadrados de três números")

let valorA = parseInt(prompt("Digite o valor de A : "))
let valorB = parseInt(prompt("Digite o valor de B : "))
let valorC = parseInt(prompt("Digite o valor de C : "))
let resultado = (valorA * valorA) + (valorB * valorB) + (valorC * valorC)

alert("A soma dos quadrados é : " + resultado)